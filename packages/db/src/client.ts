/** Postgres client factory and migration helper (postgres.js + Drizzle). */
import { fileURLToPath } from 'node:url';
import { drizzle, type PostgresJsDatabase } from 'drizzle-orm/postgres-js';
import { migrate as drizzleMigrate } from 'drizzle-orm/postgres-js/migrator';
import postgres from 'postgres';
import * as schema from './schema/index.ts';

export type Schema = typeof schema;
export type Db = PostgresJsDatabase<Schema> & { $client: postgres.Sql };

export interface CreateDbOptions {
  /** Pool size. Default 10; use 1 for scripts. */
  max?: number;
  /** Forwarded to postgres.js (e.g. `prepare: false` behind a transaction-mode pooler). */
  postgres?: postgres.Options<Record<string, postgres.PostgresType>>;
}

/** A Drizzle client over a postgres.js pool. Close it with `await db.$client.end()`. */
export function createDb(url: string, options: CreateDbOptions = {}): Db {
  const client = postgres(url, {
    max: options.max ?? 10,
    // Silence NOTICEs such as "extension already exists, skipping".
    onnotice: () => {},
    ...options.postgres,
  });
  return drizzle({ client, schema });
}

/** Committed SQL migrations generated by drizzle-kit (`pnpm --filter @oat/db db:generate`). */
export const MIGRATIONS_FOLDER = fileURLToPath(new URL('../drizzle', import.meta.url));

/** Arbitrary constant: serialises concurrent `migrate()` calls against the same database. */
const MIGRATION_LOCK_KEY = 0x0a7_db;

/**
 * Applies every pending migration in `MIGRATIONS_FOLDER`. Idempotent (applied migrations are tracked in
 * `drizzle.__drizzle_migrations`) and safe to run concurrently (session advisory lock).
 */
export async function migrate(url: string): Promise<void> {
  const db = createDb(url, { max: 1 });
  try {
    await db.$client`select pg_advisory_lock(${MIGRATION_LOCK_KEY})`;
    try {
      await drizzleMigrate(db, { migrationsFolder: MIGRATIONS_FOLDER });
    } finally {
      await db.$client`select pg_advisory_unlock(${MIGRATION_LOCK_KEY})`;
    }
  } finally {
    await db.$client.end();
  }
}
